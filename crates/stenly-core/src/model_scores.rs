/// Strip what differs between providers for the same model: an OpenRouter-style
/// vendor prefix, Ollama's `:latest`, a date suffix, and `.` vs `-` in versions.
fn norm(id: &str) -> String {
    let id = id.trim().to_ascii_lowercase();
    let id = id.rsplit('/').next().unwrap_or(&id).to_string();
    let id = id.strip_suffix(":latest").unwrap_or(&id).to_string();
    // claude-haiku-4-5-20251001 → claude-haiku-4-5
    let id = match id.rsplit_once('-') {
        Some((head, tail)) if tail.len() == 8 && tail.chars().all(|c| c.is_ascii_digit()) => head.to_string(),
        _ => id,
    };
    id.replace('.', "-")
}

/// The eval score for a model id, if it was evaluated.
pub fn score_for(model: &str) -> Option<&'static ModelScore> {
    let want = norm(model);
    if want.is_empty() {
        return None;
    }
    SCORES.iter().find(|s| norm(s.id) == want)
}

/// "8.7/10" for the UI.
pub fn label(s: &ModelScore) -> String {
    format!("{:.1}/10", s.score)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_across_provider_spellings() {
        assert_eq!(norm("anthropic/claude-sonnet-4.6"), "claude-sonnet-4-6");
        assert_eq!(norm("claude-haiku-4-5-20251001"), "claude-haiku-4-5");
        assert_eq!(norm("nemotron-3-nano:latest"), "nemotron-3-nano");
        assert_eq!(norm("qwen3:4b"), "qwen3:4b");
        assert_eq!(norm("qwen3.5:9b"), "qwen3-5:9b");
    }

    #[test]
    fn scores_are_in_range_and_unique() {
        let mut seen = std::collections::HashSet::new();
        for s in SCORES {
            assert!((0.0..=10.0).contains(&s.score), "{}", s.id);
            assert!(seen.insert(norm(s.id)), "duplicate {}", s.id);
        }
    }

    #[test]
    fn unknown_models_have_no_score() {
        assert!(score_for("").is_none());
        assert!(score_for("some-unreleased-model").is_none());
    }
}
