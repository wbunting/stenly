//! How well each summary model did on Stenly's own meeting-notes eval, shown
//! next to the model in Settings → Summaries.
//!
//! Score = fact recall (present + ½·partial over a fixed fact checklist for a
//! small set of long meetings) scaled to 0–10, minus 0.5 per major wrong
//! claim, floored at 0. The models' notes were graded blind by a separate
//! judge model. The evaluation harness and its meeting recordings are private
//! and not part of this repository; the numbers below are its published output.
//! Re-run when new models come out.

/// One evaluated model.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ModelScore {
    /// Model id as sent to the API (Ollama tag or provider model name).
    pub id: &'static str,
    /// 0.0–10.0, one decimal.
    pub score: f32,
    /// Ran on this Mac through Ollama (vs a hosted API).
    pub local: bool,
}

/// When the scores below were measured, for the UI caption.
pub const MEASURED: &str = "Oct 2026";

